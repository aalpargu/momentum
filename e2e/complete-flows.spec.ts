import { expect, test, type Page } from '@playwright/test'

async function start(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Multiplife’ı başlat' }).click()
  await expect(page.getByRole('dialog', { name: 'Multiplife ilk kurulumu' })).toBeHidden()
}
async function tab(page: Page, name: string) {
  await page.getByRole('navigation', { name: 'Ana bölümler' }).getByRole('button', { name, exact: true }).click()
}

test('journal undo refreshes the visible text and manual screen time survives reload', async ({ page }) => {
  await start(page)
  await tab(page, 'Günlük')
  const note = page.getByLabel('Bugün ne iyi gitti?')
  await note.fill('Türkçe: ıİğĞşŞöÖçÇüÜ — çalışma tamamlandı.')
  await page.getByRole('button', { name: 'Değerlendirmeyi kaydet' }).click()
  await expect(page.locator('.saved-note')).toBeVisible()
  await page.getByRole('button', { name: 'Son değişikliği geri al' }).click()
  await expect(note).toHaveValue('')
  await page.getByLabel('Uygulama veya etkinlik adı').fill('Öğrenme videosu')
  await page.getByLabel('Manuel ekran süresi dakika').fill('35')
  await page.getByLabel('Ekran süresi türü', { exact: true }).selectOption('useful')
  await page.locator('.screen-time-manual').getByRole('button', { name: 'Ekle' }).click()
  await expect(page.locator('.screen-time-entry')).toHaveCount(1)
  await page.reload()
  await expect(page.getByLabel('Öğrenme videosu dakika')).toHaveValue('35')
  await expect(page.getByLabel('Öğrenme videosu ekran süresi türü')).toHaveValue('useful')
})

test('calendar creates, rejects overlaps, edits, exports and deletes a block', async ({ page }) => {
  await start(page)
  await tab(page, 'Takvim')
  await page.getByRole('button', { name: 'Çalışma bloğu ekle', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Çalışma bloğu ekle' })
  await dialog.getByLabel('Konu').fill('Türkçe; çalışma')
  await dialog.getByLabel('Başlangıç').fill('09:00')
  await dialog.getByRole('button', { name: 'Bloğu kaydet' }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: 'Çalışma bloğu ekle', exact: true }).click()
  await dialog.getByLabel('Konu').fill('Çakışan çalışma')
  await dialog.getByLabel('Başlangıç').fill('09:30')
  await expect(dialog.getByRole('button', { name: 'Bloğu kaydet' })).toBeDisabled()
  await expect(dialog.locator('.calendar-conflict')).toContainText('Türkçe; çalışma')
  await dialog.getByRole('button', { name: 'Kapat' }).click()
  await page.locator('.agenda-row').filter({ hasText: 'Türkçe; çalışma' }).click()
  dialog = page.getByRole('dialog', { name: 'Çalışma bloğunu düzenle' })
  await dialog.getByLabel('Başlangıç').fill('11:00')
  await dialog.getByRole('button', { name: 'Bloğu kaydet' }).click()
  await expect(page.locator('.agenda-row')).toContainText('11:00–12:00')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Takvime aktar (.ics)' }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(chunk)
  expect(Buffer.concat(chunks).toString()).toContain('SUMMARY:Türkçe\\; çalışma')
  await page.locator('.agenda-row').click()
  await dialog.getByRole('button', { name: 'Bloğu sil' }).click()
  await expect(page.locator('.agenda-row')).toHaveCount(0)
})

test('a created habit records a quantity and preserves it after archiving and restoring', async ({ page }) => {
  await start(page)
  await tab(page, 'Alışkanlıklar')
  await page.getByRole('button', { name: '+ Yeni alışkanlık' }).click()
  const dialog = page.getByRole('dialog', { name: 'Alışkanlık ekle' })
  await dialog.getByLabel('İsim', { exact: true }).fill('Türkçe okuma')
  await dialog.getByLabel('Minimum', { exact: true }).fill('5 sayfa')
  await dialog.getByLabel('İdeal', { exact: true }).fill('20 sayfa')
  await dialog.getByRole('button', { name: 'Alışkanlığı ekle' }).click()
  const card = page.locator('.habit-card').filter({ hasText: 'Türkçe okuma' })
  await card.getByLabel('Türkçe okuma miktarı').fill('20')
  await card.locator('form').getByRole('button').click()
  await expect(card).toHaveClass(/habit-ideal/)
  await page.getByRole('button', { name: 'Ayarlar', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Multiplife ayarları' })
  await settings.getByRole('tab', { name: 'Alışkanlıklar' }).click()
  const row = settings.locator('.management-row').filter({ has: page.getByLabel('Türkçe okuma adı') })
  await row.getByRole('button', { name: 'Arşivle' }).click()
  await expect(row).toHaveClass(/archived/)
  await row.getByRole('button', { name: 'Etkinleştir' }).click()
  await settings.getByRole('button', { name: 'Kapat' }).click()
  await page.reload()
  await expect(card.getByLabel('Türkçe okuma miktarı')).toHaveValue('20')
  await expect(card).toHaveClass(/habit-ideal/)
})

test('all screens fit a narrow window with an unbroken task title', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await start(page)
  await page.getByLabel('Yeni önemli iş').fill('İ'.repeat(100))
  await page.getByRole('button', { name: 'Ekle', exact: true }).click()
  for (const section of ['Bugün', 'Alışkanlıklar', 'Günlük', 'İlerleme', 'Takvim']) {
    await tab(page, section)
    await expect(page.locator('main h1')).toBeVisible()
    const layout = await page.evaluate(() => ({
      viewport: innerWidth,
      width: document.documentElement.scrollWidth,
      overflow: [...document.querySelectorAll('main *')].filter(element => element.getBoundingClientRect().right > innerWidth + 0.5).map(element => ({ tag: element.tagName, className: element.className, text: element.textContent?.slice(0, 80) })),
    }))
    expect(layout.width, `${section}: ${JSON.stringify(layout)}`).toBeLessThanOrEqual(layout.viewport)
    if (section === 'Bugün' || section === 'Takvim') await page.screenshot({ path: testInfo.outputPath(section + '.png'), fullPage: true, animations: 'disabled' })
  }
})

test('JSON export can be imported, corrupt JSON cannot replace data and rollback restores it', async ({ page }) => {
  await start(page)
  await page.getByLabel('Yeni önemli iş').fill('Yedekte korunacak iş')
  await page.getByRole('button', { name: 'Ekle', exact: true }).click()
  await expect(page.locator('.plan-item')).toContainText('Yedekte korunacak iş')
  await page.getByRole('button', { name: /Senkronizasyon:/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Veri yönetimi' })
  const downloadPromise = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'JSON Yedeği İndir' }).click()
  const stream = await (await downloadPromise).createReadStream()
  const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(chunk)
  const backup = JSON.parse(Buffer.concat(chunks).toString())
  expect(backup.data.dailyPlans).toBeTruthy()
  const input = dialog.locator('input[type="file"][accept="application/json,.json"]')
  await input.setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
  await expect(dialog.locator('.import-status')).toContainText('Yedek doğrulanamadı')
  await expect(dialog.getByRole('button', { name: 'İçe aktar ve değiştir' })).toHaveCount(0)
  backup.data.dailyPlans = {}
  // A valid file above the former 5 MB limit must remain restorable.
  await input.setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup) + ' '.repeat(5 * 1024 * 1024)) })
  await expect(dialog.locator('.import-valid')).toHaveText('Geçerli')
  await dialog.getByRole('button', { name: 'İçe aktar ve değiştir' }).click()
  await page.getByRole('dialog', { name: 'Mevcut veriyi değiştir' }).getByRole('button', { name: 'Yedeği yükle' }).click()
  await expect(dialog.locator('.import-status')).toContainText('başarıyla içe aktarıldı')
  await dialog.getByRole('button', { name: 'Son içe aktarmayı geri al', exact: false }).click()
  await page.getByRole('dialog', { name: 'İçe aktarmayı geri al' }).getByRole('button', { name: 'Geri yükle', exact: true }).click()
  await expect(dialog.locator('.import-status')).toContainText('İçe aktarma geri alındı')
  await dialog.getByRole('button', { name: 'Kapat' }).click()
  await expect(page.locator('.plan-item')).toContainText('Yedekte korunacak iş')
})
